from .api_client import APIClient
from .cli import QuizCLI


# =========================================================
# MAIN APPLICATION ENTRY
# =========================================================
def main():

    # -----------------------------------------------------
    # INITIALIZE API CLIENT
    # -----------------------------------------------------
    api = APIClient()

    # -----------------------------------------------------
    # INITIALIZE CLI
    # -----------------------------------------------------
    cli = QuizCLI(api)

    # -----------------------------------------------------
    # DISPLAY BANNER
    # -----------------------------------------------------
    cli.display_banner()

    # -----------------------------------------------------
    # START APPLICATION
    # -----------------------------------------------------
    cli.run()


# =========================================================
# DIRECT EXECUTION
# =========================================================
if __name__ == "__main__":

    main()